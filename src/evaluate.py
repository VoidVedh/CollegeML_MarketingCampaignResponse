def plot_confusion_matrices(models_dict: Dict[str, Any], X_test, y_test, output_dir: str = "reports/figures") -> str:
    """
    Plots a 2x3 grid of confusion matrix heatmaps with raw counts and normalized percentages.
    """
    os.makedirs(output_dir, exist_ok=True)
    fig, axes = plt.subplots(2, 3, figsize=(15, 9))
    axes = axes.flatten()
    
    for i, (name, model) in enumerate(models_dict.items()):
        y_pred = model.predict(X_test)
        cm = confusion_matrix(y_test, y_pred)
        
        # Annotations with counts and percentages
        cm_norm = cm.astype('float') / cm.sum(axis=1)[:, np.newaxis]
        annot = np.array([
            [f"{cm[0, 0]}\n({cm_norm[0, 0]:.1%})", f"{cm[0, 1]}\n({cm_norm[0, 1]:.1%})"],
            [f"{cm[1, 0]}\n({cm_norm[1, 0]:.1%})", f"{cm[1, 1]}\n({cm_norm[1, 1]:.1%})"]
        ])
        
        sns.heatmap(
            cm,
            annot=annot,
            fmt='',
            cmap='Blues',
            cbar=False,
            ax=axes[i],
            xticklabels=['Non-Responder (0)', 'Responder (1)'],
            yticklabels=['Non-Responder (0)', 'Responder (1)'],
            linewidths=1,
            linecolor='grey'
        )
        axes[i].set_title(f"{name}", fontweight='bold', pad=8)
        axes[i].set_xlabel("Predicted Label")
        axes[i].set_ylabel("True Label")
        
    plt.suptitle("Confusion Matrix Heatmaps Across All 6 Models (Test Set, Threshold = 0.50)", fontweight='bold', fontsize=15, y=0.98)
