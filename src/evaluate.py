def plot_confusion_matrices(models_dict: Dict[str, Any], thresholds_dict: Dict[str, float], X_test, y_test, output_dir: str = "reports/figures") -> str:
    """Plots 2x3 confusion matrix grid evaluated at each model's own optimal threshold."""
    os.makedirs(output_dir, exist_ok=True)
    fig, axes = plt.subplots(2, 3, figsize=(15, 9))
    axes = axes.flatten()
    
    for i, (name, model) in enumerate(models_dict.items()):
        y_proba = model.predict_proba(X_test)[:, 1]
        t = thresholds_dict.get(name, 0.50)
        y_pred = (y_proba >= t).astype(int)
        cm = confusion_matrix(y_test, y_pred)
        
        cm_norm = cm.astype('float') / cm.sum(axis=1)[:, np.newaxis]
        annot = np.array([
            [f"{cm[0, 0]}\n({cm_norm[0, 0]:.1%})", f"{cm[0, 1]}\n({cm_norm[0, 1]:.1%})"],
            [f"{cm[1, 0]}\n({cm_norm[1, 0]:.1%})", f"{cm[1, 1]}\n({cm_norm[1, 1]:.1%})"]
        ])
        
        sns.heatmap(
            cm,
            annot=annot,
            fmt='',
            cmap='Blues',
            cbar=False,
            ax=axes[i],
            xticklabels=['Non-Responder', 'Responder'],
            yticklabels=['Non-Responder', 'Responder'],
            linewidths=1,
            linecolor='grey'
        )
        axes[i].set_title(f"{name} (t = {t:.2f})", fontweight='bold', pad=8)
        axes[i].set_xlabel("Predicted")
        axes[i].set_ylabel("Actual")
        
    plt.suptitle("Confusion Matrix Heatmaps Evaluated at Each Model's Out-Of-Fold Optimal Threshold", fontweight='bold', fontsize=14, y=0.98)
    plt.tight_layout()
    
    filepath = os.path.join(output_dir, "confusion_matrices_grid.png")
    plt.savefig(filepath, dpi=300)
    plt.close()
    return filepath


def plot_cumulative_gains_and_lift(best_model, X_test, y_test, output_dir: str = "reports/figures") -> str:
    """Computes and plots Cumulative Gains and Decile Lift charts."""
    os.makedirs(output_dir, exist_ok=True)
    y_proba = best_model.predict_proba(X_test)[:, 1]
    
    df_eval = pd.DataFrame({'actual': np.asarray(y_test), 'prob': y_proba})
    df_eval = df_eval.sort_values(by='prob', ascending=False).reset_index(drop=True)
    df_eval['decile'] = pd.qcut(df_eval.index, q=10, labels=range(1, 11))
    
    total_responders = df_eval['actual'].sum()
    total_customers = len(df_eval)
    
    df_eval['cum_responders'] = df_eval['actual'].cumsum()
    df_eval['cum_pct_responders'] = (df_eval['cum_responders'] / total_responders) * 100
    df_eval['cum_pct_customers'] = ((df_eval.index + 1) / total_customers) * 100
    
    decile_summary = df_eval.groupby('decile', observed=False).agg(
        total_in_decile=('actual', 'count'),
        responders_in_decile=('actual', 'sum')
    ).reset_index()
    decile_summary['response_rate'] = (decile_summary['responders_in_decile'] / decile_summary['total_in_decile']) * 100
    baseline_rate = (total_responders / total_customers) * 100
    decile_summary['lift'] = decile_summary['response_rate'] / baseline_rate
    
    fig, axes = plt.subplots(1, 2, figsize=(14, 6))
    
    # Gains
    axes[0].plot(df_eval['cum_pct_customers'], df_eval['cum_pct_responders'], label='ML Model Gains', color='#1f77b4', lw=2.5)
    axes[0].plot([0, 100], [0, 100], 'k--', label='Random Targeting', lw=1.5)
    for pct in [20, 30]:
        idx = int(total_customers * (pct / 100)) - 1
        gain = df_eval.loc[idx, 'cum_pct_responders']
        axes[0].scatter([pct], [gain], color='#d62728', s=60, zorder=5)
        axes[0].annotate(f"Top {pct}%: {gain:.1f}% responders",
                         xy=(pct, gain), xytext=(pct + 5, gain - 8),
                         arrowprops=dict(facecolor='black', shrink=0.05, width=1, headwidth=5),
                         fontweight='bold')
    axes[0].set_title("Cumulative Gains Chart", fontweight='bold')
    axes[0].set_xlabel("Percentage of Customers Contacted (%)")
    axes[0].set_ylabel("Cumulative % Responders Captured")
    axes[0].set_xlim([0, 100])
    axes[0].set_ylim([0, 105])
    axes[0].legend(loc='lower right', frameon=True)
    
    # Lift
    sns.barplot(data=decile_summary, x='decile', y='lift', color='#2ca02c', ax=axes[1], edgecolor='black', alpha=0.85)
    axes[1].axhline(1.0, color='red', linestyle='--', lw=1.5, label='Baseline Lift (1.0x)')
    axes[1].set_title("Decile Lift Curve", fontweight='bold')
    axes[1].set_xlabel("Customer Decile (Ranked by Propensity)")
    axes[1].set_ylabel("Lift Multiplier vs Random")
    for p in axes[1].patches:
        height = p.get_height()
        if height > 0:
            axes[1].annotate(f"{height:.2f}x",
                             (p.get_x() + p.get_width() / 2., height),
                             ha='center', va='bottom', xytext=(0, 3),
                             textcoords='offset points', fontweight='bold', fontsize=9)
    axes[1].legend(loc='upper right', frameon=True)
    
    plt.suptitle("Targeting Efficiency: Gains and Decile Lift Analysis", fontweight='bold', fontsize=14, y=1.01)
    plt.tight_layout()
    
    filepath = os.path.join(output_dir, "cumulative_gains_lift.png")
    plt.savefig(filepath, dpi=300)
    plt.close()
    return filepath


def analyze_feature_importances(
    best_tree_model, lr_model,
    X_test, y_test,
    feature_names: List[str],
    output_dir: str = "reports/figures"
) -> Dict[str, Any]:
    """Generates Tree MDI, Permutation Importance, Odds Ratios, and SHAP plots."""
    os.makedirs(output_dir, exist_ok=True)
    plots = {}
    
    # 1. Tree-based MDI
    tree_estimator = best_tree_model.named_steps.get('classifier', best_tree_model)
    if hasattr(tree_estimator, 'feature_importances_'):
        importances = tree_estimator.feature_importances_
        fi_df = pd.DataFrame({'feature': feature_names, 'importance': importances})
        fi_df = fi_df.sort_values('importance', ascending=True)
        if len(fi_df) > 20:
            fi_df = fi_df.tail(20)
        
        plt.figure(figsize=(10, 7))
        plt.barh(fi_df['feature'], fi_df['importance'], color='#1f77b4', edgecolor='black', alpha=0.85)
        plt.title("Tree-Based Feature Importances (Top 20 MDI)", fontweight='bold', pad=12)
        plt.xlabel("Relative Importance")
        plt.tight_layout()
        fi_path = os.path.join(output_dir, "feature_importance_tree.png")
        plt.savefig(fi_path, dpi=300)
        plt.close()
        plots['tree_importance'] = fi_path
        
    # 2. Permutation Importance
    perm_res = permutation_importance(best_tree_model, X_test, y_test, n_repeats=5, random_state=42, scoring='f1')
    perm_df = pd.DataFrame({
        'feature': X_test.columns,
        'mean_importance': perm_res.importances_mean,
        'std': perm_res.importances_std
    }).sort_values('mean_importance', ascending=True)
    if len(perm_df) > 20:
        perm_df = perm_df.tail(20)
    
    plt.figure(figsize=(10, 7))
    plt.barh(perm_df['feature'], perm_df['mean_importance'], xerr=perm_df['std'], color='#2ca02c', edgecolor='black', alpha=0.85)
    plt.title("Permutation Feature Importance on Test Set (Top F1 Degradation)", fontweight='bold', pad=12)
    plt.xlabel("Mean F1-Score Decrease Upon Feature Permutation")
    plt.tight_layout()
    perm_path = os.path.join(output_dir, "feature_importance_permutation.png")
    plt.savefig(perm_path, dpi=300)
    plt.close()
    plots['permutation_importance'] = perm_path
    
    # 3. Logistic Regression Odds Ratios
    lr_estimator = lr_model.named_steps.get('classifier', lr_model)
    if hasattr(lr_estimator, 'coef_'):
        coefs = lr_estimator.coef_[0]
        odds_ratios = np.exp(coefs)
        or_df = pd.DataFrame({
            'feature': feature_names,
            'odds_ratio': odds_ratios,
            'abs_log_or': np.abs(coefs)
        }).sort_values('abs_log_or', ascending=True)
        if len(or_df) > 20:
            or_df = or_df.tail(20)
        or_df = or_df.sort_values('odds_ratio', ascending=True)
        
        plt.figure(figsize=(10, 7))
        colors = ['#d62728' if x < 1.0 else '#1f77b4' for x in or_df['odds_ratio']]
        plt.barh(or_df['feature'], or_df['odds_ratio'], color=colors, edgecolor='black', alpha=0.85)
        plt.axvline(1.0, color='k', linestyle='--', lw=1.2, label='Baseline (Odds Ratio = 1.0)')
        plt.title("Logistic Regression Predictors: Odds Ratios (Top 20 Drivers)", fontweight='bold', pad=12)
        plt.xlabel("Odds Ratio (> 1.0 indicates elevated subscription odds)")
        plt.legend(loc='lower right')
        plt.tight_layout()
        or_path = os.path.join(output_dir, "feature_importance_odds_ratios.png")
        plt.savefig(or_path, dpi=300)
        plt.close()
        plots['odds_ratios'] = or_path
        
    # 4. SHAP Summary Plot
    try:
        import shap
        preprocessor = best_tree_model.named_steps['preprocessor']
        sample_size = min(300, len(X_test))
        X_test_sub = X_test.sample(sample_size, random_state=42)
        X_test_trans = preprocessor.transform(X_test_sub)
        explainer = shap.TreeExplainer(tree_estimator)
        shap_values = explainer.shap_values(X_test_trans)
        
        if isinstance(shap_values, list):
            sv = shap_values[1]
        elif hasattr(shap_values, 'shape') and len(shap_values.shape) == 3:
            sv = shap_values[:, :, 1]
        else:
            sv = shap_values
            
        plt.figure(figsize=(10, 7))
        shap.summary_plot(sv, X_test_trans, feature_names=feature_names, max_display=15, show=False)
        plt.title("SHAP Feature Attribution & Impact Distribution (Top 15 Drivers)", fontweight='bold', pad=15)
        plt.tight_layout()
        shap_path = os.path.join(output_dir, "shap_summary.png")
        plt.savefig(shap_path, dpi=300, bbox_inches='tight')
        plt.close()
        plots['shap'] = shap_path
    except Exception as e:
        print(f"SHAP explanation note: {e}")
        plots['shap'] = None
        
    return plots
