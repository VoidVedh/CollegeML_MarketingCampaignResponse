def plot_roc_curves(models_dict: Dict[str, Any], X_test, y_test, output_dir: str = "reports/figures") -> str:
    """Plots Receiver Operating Characteristic (ROC) curves."""
    os.makedirs(output_dir, exist_ok=True)
    plt.figure(figsize=(9, 7))
    palette = sns.color_palette("tab10", len(models_dict))
    
    for i, (name, model) in enumerate(models_dict.items()):
        y_proba = model.predict_proba(X_test)[:, 1]
        fpr, tpr, _ = roc_curve(y_test, y_proba)
        auc_score = roc_auc_score(y_test, y_proba)
        plt.plot(fpr, tpr, label=f"{name} (AUC = {auc_score:.3f})", color=palette[i], lw=2)
        
    plt.plot([0, 1], [0, 1], 'k--', lw=1.5, label='Random Guessing (AUC = 0.500)')
    plt.xlim([-0.02, 1.02])
    plt.ylim([-0.02, 1.02])
    plt.xlabel("False Positive Rate (1 - Specificity)")
    plt.ylabel("True Positive Rate (Sensitivity / Recall)")
